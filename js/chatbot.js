// Initialize chatbot
const chatBox = document.getElementById('chat-box');
const chatInput = document.getElementById('chat-input');

// Send message
chatInput.addEventListener('keypress', function (e) {
  if (e.key === 'Enter') {
    const userInput = chatInput.value.trim();
    if (userInput) {
      appendMessage('You', userInput);
      respondToUser(userInput.toLowerCase());
      chatInput.value = '';
    }
  }
});

// Append messages to the chat
function appendMessage(sender, message) {
  const messageDiv = document.createElement('div');
  messageDiv.innerHTML = `<strong>${sender}:</strong> ${message}`;
  chatBox.appendChild(messageDiv);
  chatBox.scrollTop = chatBox.scrollHeight;
}

// Respond based on keyword
function respondToUser(query) {
  const keys = Object.keys(sportsData);
  const foundKey = keys.find(key => query.includes(key.toLowerCase()));

  if (foundKey) {
    const sport = sportsData[foundKey];
    const response = `
      <div><strong>${sport.name}</strong> (${sport.category})</div>
      <img src="${sport.image}" alt="${sport.name}" style="width:100%; margin:5px 0;" />
      <div><em><strong>About:</strong></em> ${sport.about || sport.history}</div>
      <div><em><strong>Rules:</strong></em> <ul>${sport.rules.map(r => `<li>${r}</li>`).join('')}</ul></div>
      <div><em><strong>News:</strong></em> ${sport.news}</div>
    `;
    appendMessage('Bot', response);
  } else {
    appendMessage('Bot', "Sorry, I don't have info on that. Try a sport like 'MMA', 'hurdles', or 'curling'.");
  }
}
